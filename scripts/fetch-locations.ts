// Fetches Turkey's provinces and districts from Wikidata (CC0) and writes src/data/locations.ts.
// Run `npm run fetch:locations`. The output is committed; the app never calls Wikidata.
import { writeFileSync } from "node:fs";

const QUERY = `
SELECT ?district ?trLabel ?enLabel ?provinceLabel WHERE {
  ?district wdt:P31 wd:Q1147395 ; wdt:P131 ?province .
  ?province wdt:P31 wd:Q48336 .
  FILTER NOT EXISTS { ?district wdt:P576 ?dissolved }
  OPTIONAL { ?district rdfs:label ?trLabel FILTER(LANG(?trLabel) = "tr") }
  OPTIONAL { ?district rdfs:label ?enLabel FILTER(LANG(?enLabel) = "en") }
  SERVICE wikibase:label { bd:serviceParam wikibase:language "tr". ?province rdfs:label ?provinceLabel. }
}`;

// The three seeded cities are checked against the official district lists (İçişleri Bakanlığı).
const OFFICIAL: Record<string, string[]> = {
  "İstanbul": ["Adalar", "Arnavutköy", "Ataşehir", "Avcılar", "Bağcılar", "Bahçelievler", "Bakırköy", "Başakşehir", "Bayrampaşa",
    "Beşiktaş", "Beykoz", "Beylikdüzü", "Beyoğlu", "Büyükçekmece", "Çatalca", "Çekmeköy", "Esenler", "Esenyurt", "Eyüpsultan",
    "Fatih", "Gaziosmanpaşa", "Güngören", "Kadıköy", "Kağıthane", "Kartal", "Küçükçekmece", "Maltepe", "Pendik", "Sancaktepe",
    "Sarıyer", "Silivri", "Sultanbeyli", "Sultangazi", "Şile", "Şişli", "Tuzla", "Ümraniye", "Üsküdar", "Zeytinburnu"],
  "Ankara": ["Akyurt", "Altındağ", "Ayaş", "Balâ", "Beypazarı", "Çamlıdere", "Çankaya", "Çubuk", "Elmadağ", "Etimesgut", "Evren",
    "Gölbaşı", "Güdül", "Haymana", "Kahramankazan", "Kalecik", "Keçiören", "Kızılcahamam", "Mamak", "Nallıhan", "Polatlı",
    "Pursaklar", "Sincan", "Şereflikoçhisar", "Yenimahalle"],
  "İzmir": ["Aliağa", "Balçova", "Bayındır", "Bayraklı", "Bergama", "Beydağ", "Bornova", "Buca", "Çeşme", "Çiğli", "Dikili", "Foça",
    "Gaziemir", "Güzelbahçe", "Karabağlar", "Karaburun", "Karşıyaka", "Kemalpaşa", "Kınık", "Kiraz", "Konak", "Menderes",
    "Menemen", "Narlıdere", "Ödemiş", "Seferihisar", "Selçuk", "Tire", "Torbalı", "Urla"],
};

const CENTERS: Record<string, [number, number]> = {
  "İstanbul": [41.0082, 28.9784], "Ankara": [39.9334, 32.8597], "İzmir": [38.4237, 27.1428],
};

/** Drops Wikidata disambiguation: any trailing "(…)" and a trailing "ilçe/ilçesi/district". */
function clean(label: string): string {
  return label
    .normalize("NFC")
    .replace(/\s*\([^)]*\)\s*$/u, "")
    .replace(/\s+(i̇?lçe(si)?|İlçe(si)?|ilce(si)?|district)\s*$/iu, "")
    .trim();
}

async function main() {
  const url = `https://query.wikidata.org/sparql?query=${encodeURIComponent(QUERY)}`;
  const res = await fetch(url, {
    headers: { Accept: "application/sparql-results+json", "User-Agent": "likeminded-portfolio (https://github.com/aslihantokalak/likemindedincity)" },
  });
  if (!res.ok) throw new Error(`Wikidata returned ${res.status}`);
  type Binding = Record<string, { value: string } | undefined>;
  const rows: Binding[] = (await res.json()).results.bindings;

  const byProvince = new Map<string, Set<string>>();
  for (const r of rows) {
    const province = r.provinceLabel!.value;
    const label = r.trLabel?.value ?? r.enLabel?.value;
    if (!label || /^Q\d+$/.test(label)) continue;
    // A district labelled with its province's name is the central district.
    const cleaned = clean(label);
    const name = cleaned === province ? "Merkez" : cleaned;
    if (!byProvince.has(province)) byProvince.set(province, new Set());
    byProvince.get(province)!.add(name);
  }
  for (const [province, districts] of Object.entries(OFFICIAL)) byProvince.set(province, new Set(districts));

  const collate = (a: string, b: string) => a.localeCompare(b, "tr");
  const provinces = [...byProvince.keys()].sort(collate).map(name => ({
    name,
    districts: [...byProvince.get(name)!].sort(collate),
    ...(CENTERS[name] ? { center: CENTERS[name] } : {}),
  }));
  if (provinces.length !== 81) throw new Error(`Expected 81 provinces, got ${provinces.length}`);

  const total = provinces.reduce((n, p) => n + p.districts.length, 0);
  const out = `// Generated by scripts/fetch-locations.ts on ${new Date().toISOString().slice(0, 10)}. Do not edit by hand.
// Source: Wikidata (https://www.wikidata.org), districts of Turkey (Q1147395) in provinces (Q48336), CC0 1.0.
// İstanbul, Ankara and İzmir are replaced with the official district lists. Other provinces come straight from
// Wikidata after label clean-up and may contain small errors; ${total} districts in total (official count: 973).
export type Province = { name: string; districts: string[]; center?: [number, number] };

export const PROVINCES: Province[] = ${JSON.stringify(provinces, null, 2)};

export const districtsOf = (province: string): string[] => PROVINCES.find(p => p.name === province)?.districts ?? [];
`;
  writeFileSync(new URL("../src/data/locations.ts", import.meta.url), out);
  console.log(`Wrote ${provinces.length} provinces, ${total} districts`);
}

await main();
